import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { COMPACT_CHECKPOINT_PROMPT } from '../src/core/checkpoint-prompt.mjs';
const input=resolve(process.argv[2]);
const output=resolve(process.argv[3]);
const payload=JSON.parse(await readFile(input,'utf8'));
if (!payload.model.startsWith('qwen3.5:9b')) throw new Error('This replay is local 9B only');
const user=payload.messages.findLast(m=>m.role==='user');
const source=typeof user.content==='string'?user.content:user.content.map(b=>b.text??'').join('\n');
const end=Math.max(source.lastIndexOf('</conversation>')+'</conversation>'.length,source.lastIndexOf('</previous-summary>')+'</previous-summary>'.length);
if(end<20)throw new Error('Expected native Pi summary envelope');
user.content=source.slice(0,end)+'\n\n'+COMPACT_CHECKPOINT_PROMPT;
payload.stream=false;
delete payload.stream_options;
const started=Date.now();
const response=await fetch('http://127.0.0.1:11434/v1/chat/completions',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(payload),signal:AbortSignal.timeout(180000)});
if(!response.ok)throw new Error(`Local replay HTTP ${response.status}`);
const result=await response.json();
await mkdir(output,{recursive:true});
await writeFile(resolve(output,'result.json'),JSON.stringify({input,durationMs:Date.now()-started,finishReason:result.choices[0].finish_reason,usage:result.usage,summary:result.choices[0].message.content},null,2));
console.log(JSON.stringify({output,finishReason:result.choices[0].finish_reason,usage:result.usage}));
